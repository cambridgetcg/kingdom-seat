// OpenSSH encodings for the keys a mirror publishes and the signatures its
// commits carry (KS-004 4.4, 4.5): the host key that signs host-attested
// ledger entries and, for a registered citizen, the op key that signs its
// own, written as an `allowed_signers` file a reader can hand to
// `ssh-keygen -Y verify` or `git verify-commit`; and the SSHSIG format the
// signer signs a mirror commit in. Public keys and signatures only; the
// signer holds every seed, and signs here only in the git namespace.
import { sha512 } from "@noble/hashes/sha2.js";
import { concatBytes, fromB64, toB64, utf8 } from "./crypto.ts";
import { Refusal } from "./types.ts";

/** The principal the host key is published under, and the namespace every published key is limited to. */
export const HOST_PRINCIPAL = "host@kingdom-seat";
export const GIT_NAMESPACE = "git";

function sshString(bytes: Uint8Array): Uint8Array {
  const len = new Uint8Array(4);
  new DataView(len.buffer).setUint32(0, bytes.length, false);
  return concatBytes(len, bytes);
}

/** The SSH wire blob of an Ed25519 public key: string "ssh-ed25519", string key (RFC 8709). */
export function sshEd25519Blob(publicKey: Uint8Array): Uint8Array {
  if (!(publicKey instanceof Uint8Array) || publicKey.length !== 32) throw new Refusal("invalid-request", "an Ed25519 public key is 32 bytes");
  return concatBytes(sshString(utf8("ssh-ed25519")), sshString(publicKey));
}

/** "ssh-ed25519 <base64 blob>", as authorized_keys and allowed_signers spell a key. */
export function sshPublicKey(publicKey: Uint8Array): string {
  return `ssh-ed25519 ${toB64(sshEd25519Blob(publicKey))}`;
}

/* ── SSHSIG (OpenSSH PROTOCOL.sshsig), Ed25519 and SHA-512 only ─────── */

const SSHSIG_MAGIC = utf8("SSHSIG");
const SSHSIG_HASH = "sha512";
/** A git commit or tag object is small; anything larger is not one, and is refused rather than signed. */
export const SSHSIG_MAX_MESSAGE_BYTES = 1024 * 1024;

/**
 * The bytes an SSHSIG signature covers: the magic, the namespace, an empty
 * reserved field, the hash name and the message's SHA-512. The magic and
 * the namespace keep it from passing as any other signature the same key
 * makes: a ledger entry or a thought is a bare 32-byte digest.
 */
export function sshsigSignedData(namespace: string, message: Uint8Array): Uint8Array {
  if (namespace !== GIT_NAMESPACE) throw new Refusal("invalid-request", "this host makes SSH signatures for the git namespace only");
  if (!(message instanceof Uint8Array) || message.length > SSHSIG_MAX_MESSAGE_BYTES) throw new Refusal("oversize", "not a message this host signs");
  return concatBytes(SSHSIG_MAGIC, sshString(utf8(namespace)), sshString(new Uint8Array()), sshString(utf8(SSHSIG_HASH)), sshString(sha512(message)));
}

/** The armoured signature `ssh-keygen -Y sign` writes, for a 64-byte Ed25519 signature over sshsigSignedData. */
export function sshsigArmor(publicKey: Uint8Array, namespace: string, signature: Uint8Array): string {
  if (signature.length !== 64) throw new Refusal("invalid-request", "an Ed25519 signature is 64 bytes");
  const version = new Uint8Array([0, 0, 0, 1]);
  const sigBlob = concatBytes(sshString(utf8("ssh-ed25519")), sshString(signature));
  const blob = concatBytes(SSHSIG_MAGIC, version, sshString(sshEd25519Blob(publicKey)), sshString(utf8(namespace)), sshString(new Uint8Array()), sshString(utf8(SSHSIG_HASH)), sshString(sigBlob));
  const b64 = toB64(blob);
  const lines: string[] = [];
  for (let i = 0; i < b64.length; i += 70) lines.push(b64.slice(i, i + 70));
  return `-----BEGIN SSH SIGNATURE-----\n${lines.join("\n")}\n-----END SSH SIGNATURE-----\n`;
}

/** The Ed25519 public key in an "ssh-ed25519 <base64>" line, as git hands its signing key file over. */
export function parseSshEd25519(line: string): Uint8Array {
  const m = /^ssh-ed25519 ([A-Za-z0-9+/]+={0,2})(?: [^\r\n]*)?\r?\n?$/.exec(line);
  if (!m) throw new Refusal("invalid-request", "not one ssh-ed25519 public key");
  const blob = fromB64(m[1]!);
  const key = blob.slice(blob.length - 32);
  if (blob.length !== 4 + 11 + 4 + 32 || toB64(sshEd25519Blob(key)) !== m[1]) throw new Refusal("invalid-request", "not one ssh-ed25519 public key");
  return key;
}

/** The citizen's own principal, for its op key. */
export function citizenPrincipal(word: string): string {
  return `${word}@kingdom-seat`;
}

/**
 * An allowed_signers file (ssh-keygen(1), ALLOWED SIGNERS): one line per
 * key, its principal, limited to the git namespace, so a published key
 * vouches for mirror commits and nothing else; comment lines say what each
 * key is. Keys are deduplicated, first naming wins.
 */
export function allowedSigners(keys: { principal: string; public_key: Uint8Array; comment: string }[]): string {
  const lines = ["# Generated by kingdom-seat; never edited by hand. Public keys only."];
  const seen = new Set<string>();
  for (const k of keys) {
    if (!/^[A-Za-z0-9._@-]{1,128}$/.test(k.principal)) throw new Refusal("invalid-request", "a principal is one plain token");
    if (/[\r\n]/.test(k.comment)) throw new Refusal("invalid-request", "a comment is one line");
    const key = sshPublicKey(k.public_key);
    if (seen.has(key)) continue;
    seen.add(key);
    lines.push(`# ${k.comment}`, `${k.principal} namespaces="${GIT_NAMESPACE}" ${key}`);
  }
  return `${lines.join("\n")}\n`;
}
